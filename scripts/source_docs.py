"""Write the steel deck's traceability docs: `py -3.11 scripts/source_docs.py [--check]`.

Generates docs/steel_traceability.md and the provision table of docs/steel_connections.md §4
(between its BEGIN and END markers) from three sources:

  - petra/models/steel/trace.py, each provision's treatment;
  - docs/sources/inventory.jsonl, each value Petra takes from a standard with its clause,
    which tests/test_sources.py keeps equal to the registry;
  - docs/sources/anchors.jsonl and equations.json, the page that states each value and the
    equations Chapters J and K number.

`provisions` reads an item's clause for the provisions it names. --check exits 1 when a
committed file differs from what the sources give.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT))

import source_inventory as inv  # noqa: E402
import verify_sources as vs  # noqa: E402
from petra.models.steel import trace  # noqa: E402

TRACEABILITY = ROOT / "docs" / "steel_traceability.md"
CONNECTIONS = ROOT / "docs" / "steel_connections.md"
BEGIN = "<!-- BEGIN provisions: generated by scripts/source_docs.py from trace.py and docs/sources -->"
END = "<!-- END provisions -->"

STEEL = ("AISC 360-22", "RCSC 2025", "AISC Manual 16th ed.")
"""The editions whose values the steel deck reads, besides the Shapes Database."""
SHAPES = "AISC Shapes Database v16.0"

CHAPTERS = {
    "J1": "General provisions", "J2": "Welds and welded joints", "J3": "Bolts and threaded parts",
    "J4": "Affected elements of members and connecting elements", "J5": "Fillers", "J6": "Splices",
    "J7": "Bearing strength", "J8": "Column bases and bearing on concrete", "J9": "Anchor rods and embedments",
    "J10": "Flanges and webs with concentrated forces",
}
"""A short name for each Chapter J section, for the §4 table. Chapter K's are trace.py's."""

TABLES = {"J2.4": "J2.2b", "J2.5": "J2.4", "J3.1": "J3.2", "J3.2": "J3.7", "J3.3": "J3.3", "J3.4": "J3.5",
          "J3.5": "J3.5"}
"""The provision that sets each Chapter J table's use: Table J3.4's distances are J3.5's."""

APPENDIX3_EQUATIONS = {"A-3-1": "App. 3.3a", "A-3-2": "App. 3.3b", "A-3-3": "App. 3.3c", "A-3-4": "App. 3.3c",
                       "A-3-5": "App. 3.3c", "A-3-6": "App. 3.3c", "A-3-7": "App. 3.4b"}

DOCS = {inv.A360: "AISC 360-22", inv.P901: "Companion vol. 1", inv.P902: "Companion vol. 2"}

ROWS = trace.ALL
IDS = tuple(dict.fromkeys(p.section for p in ROWS))
TREATMENT: dict[str, str] = {}
for _p in ROWS:  # a section split by paragraph is excluded only when every paragraph is
    if TREATMENT.get(_p.section, "excluded") == "excluded":
        TREATMENT[_p.section] = _p.treatment
JK = tuple(p.section for p in trace.TABLE)


# --- Which provisions a clause names -----------------------------------------------------------

SECTION = re.compile(r"\b(?:Sections?|Commentary Section) ([JK]\d+(?:\.\d+[a-z]?)?)(?:\([a-z0-9]+\))*(?:-([JK]\d+\.\d+))?")
TABLE = re.compile(r"\bTable ([JK]\d+\.\d+)")
EQUATIONS = re.compile(r"\bEqs?\. ([A-Z]?-?\d+-\d+[a-z]?(?:(?:, | and )[A-Z]?-?\d+-\d+[a-z]?)*)")
APPENDIX = re.compile(r"Appendix 3, Sections? (\d\.\d)(?:\(([a-z])\))?")
PARTS = re.compile(r"\bParts? (\d+(?:(?:, | and )\d+)*)")


def resolve(number: str) -> list[str]:
    """The traced provisions a section number names: itself, or its lettered parts that are
    not excluded ("J3.11" is J3.11a), or its chapter's ("K3.2" is K3)."""
    if number in TREATMENT:
        return [number]
    parts = [i for i in IDS if i.startswith(number) and i[len(number):].isalpha() and TREATMENT[i] != "excluded"]
    if parts:
        return parts
    for shorter in (number.rstrip("abcdefgh"), number.split(".")[0]):
        if shorter in TREATMENT:
            return [shorter]
    return []


def equation_sections() -> dict[str, str]:
    """Each Chapter J and K equation label -> the provision whose heading it follows."""
    return {label: section for label, section, _ in vs.read_equations()["equations"]}


RCSC = re.compile(r"Section (\d+(?:\.\d+)?)")


def rcsc_sections(items: list[dict]) -> dict[str, str]:
    """RCSC section -> the AISC 360-22 section the inventory says it equals, from clauses as
    "Section 5.4 (= AISC 360-22 Section J3.9)"."""
    out = {}
    for x in items:
        m = re.match(r"Section (\d+(?:\.\d+)?)\S* \(= AISC 360-22 Section ([JK][\d.]+[a-z]?)\)", x["clause"])
        if x["edition"] == "RCSC 2025" and m:
            out[m.group(1)] = m.group(2)
    return out


def provisions(item: dict, eqs: dict[str, str], rcsc: dict[str, str]) -> list[str]:
    """The traced provisions an inventory item's clause names, in trace order."""
    clause, edition = item["clause"], item["edition"]
    found: list[str] = []
    for m in SECTION.finditer(clause):
        found += resolve(m.group(1)) + (resolve(m.group(2)) if m.group(2) else [])
    for m in TABLE.finditer(clause):
        found += resolve(TABLES.get(m.group(1), m.group(1)))
    labels = [x for m in EQUATIONS.finditer(clause) for x in re.split(r", | and ", m.group(1))]
    if item["id"].startswith("eq.aisc360."):
        labels.append(item["id"].removeprefix("eq.aisc360."))
    for label in labels:
        if label in eqs:
            found += resolve(eqs[label])
        elif label in APPENDIX3_EQUATIONS:
            found.append(APPENDIX3_EQUATIONS[label])
    m = APPENDIX.search(clause)
    if m and not any(i.startswith("App.") for i in found):
        found += resolve(f"App. {m.group(1)}{m.group(2) or ''}")
    m = RCSC.match(clause)
    if edition == "RCSC 2025" and m and "(= AISC" not in clause:
        number = m.group(1)
        found += resolve(rcsc[number]) if number in rcsc else resolve(f"RCSC {number.split('.')[0]}")
    if edition == "AISC Manual 16th ed.":
        parts = [x for m in PARTS.finditer(clause) for x in re.split(r", | and ", m.group(1))]
        if item["id"].startswith("eq.manual."):
            parts.append(item["id"].removeprefix("eq.manual.").split("-")[0])
        found += [f"Manual Part {p}" for p in parts if f"Manual Part {p}" in TREATMENT]
    return [i for i in IDS if i in found]


def steel_items() -> list[dict]:
    return [x for x in inv.read() if x["edition"] in STEEL]


# --- Rendering ---------------------------------------------------------------------------------

def cell(text: str) -> str:
    return str(text).replace("|", "\\|")


def where(anchor: dict) -> str:
    """Where an anchor says the value is stated."""
    kind = anchor["kind"]
    if kind == "text":
        return f"{DOCS[anchor['doc']]} p. {anchor['page']}"
    if kind == "visual":
        return f"{DOCS[anchor['doc']]} p. {anchor['page']}, from the page image"
    if kind == "cell":
        return f"cell {anchor['page']}"
    if kind == "designation":
        return "its name"
    return f"absent: {anchor['reason']}"


def tally(rows) -> str:
    """"checks 29, enforces 5 as rules, states 4 as premises and excludes 20"."""
    n = Counter(p.treatment for p in rows)
    return (f"checks {n['check']}, enforces {n['rule']} as {'a rule' if n['rule'] == 1 else 'rules'}, "
            f"states {n['premise']} as premises and excludes {n['excluded']}")


def percent(n: int, d: int) -> str:
    return f"{round(100 * n / d)}%"


def coverage() -> dict:
    """Chapters J and K's provisions and equations, and which of them Petra encodes."""
    eqs = equation_sections()
    items = inv.read()
    cited = {label for x in items for m in EQUATIONS.finditer(x["clause"])
             for label in re.split(r", | and ", m.group(1)) if x["edition"] == "AISC 360-22"}
    cited |= {x["id"].removeprefix("eq.aisc360.") for x in items if x["id"].startswith("eq.aisc360.")}
    encoded = [p.section for p in trace.TABLE if p.treatment in ("check", "rule")]
    by_section: dict[str, list[str]] = {}
    for label, raw in eqs.items():
        for section in resolve(raw) or [raw]:
            by_section.setdefault(section, []).append(label)
    return {"provisions": len(JK), "encoded": encoded, "equations": list(eqs), "cited": sorted(cited & set(eqs)),
            "by_section": by_section,
            "excluded": [p.section for p in trace.TABLE if p.treatment == "excluded"],
            "premise": [p.section for p in trace.TABLE if p.treatment == "premise"]}


def values_by_provision() -> tuple[dict[str, list[dict]], list[dict]]:
    """Traced provision -> the steel items whose clause names it, and the items naming none."""
    eqs = equation_sections()
    items = steel_items()
    rcsc = rcsc_sections(items)
    named: dict[str, list[dict]] = {i: [] for i in IDS}
    other = []
    for x in items:
        found = provisions(x, eqs, rcsc)
        for i in found:
            named[i].append(x)
        if not found:
            other.append(x)
    return named, other


def value_table(items: list[dict], anchors: dict[str, dict]) -> list[str]:
    lines = ["| Item | Petra | Printed | Stated at |", "|---|---|---|---|"]
    for x in items:
        a = anchors[x["id"]]
        if x["id"].startswith("eq.") or len(x["value"]) > 40:
            petra = f"`{x['symbol']}`"
        else:
            petra = cell(f"{x['value']} {x['unit'] if x['unit'] != '1' else ''}".strip())
        printed = a.get("value") if a["kind"] == "designation" else a.get("printed", "")
        lines.append(f"| `{x['id']}` | {petra} | {cell(printed or '')} | {cell(where(a))} |")
    return lines


def traceability() -> str:
    """docs/steel_traceability.md."""
    anchors = {a["id"]: a for a in vs.read_anchors()}
    named, other = values_by_provision()
    c = coverage()
    lines = [
        "# Clause traceability of the steel deck",
        "",
        "`py -3.11 scripts/source_docs.py` generates this file from `petra/models/steel/trace.py` and "
        "`docs/sources/`. `tests/test_sources.py` fails when it is stale, and `tests/test_steel_trace.py` "
        "fails when a provision is unmapped. Every count here is measured from those files.",
        "",
        "Each row gives its provision one treatment:",
        "",
        "- **check** means the checks of the modes in the row encode the provision.",
        "- **rule** means the deck enforces the provision where it reads the design or factors the strength.",
        "- **premise** means the deck states the provision as an assumption and does not check it.",
        "- **excluded** means the provision is outside v1.0.",
        "",
        "The values column counts the registry values, equations and coded rules whose clause names the "
        "provision. The values section lists each one with the page that states it.",
        "",
        "| Provision | Title | Treatment | Modes | Values | Note |",
        "|---|---|---|---|---|---|",
    ]
    counted = set()
    for p in ROWS:  # a section split by paragraph counts its values on its first paragraph that is not excluded
        modes = ", ".join(f"`{m}`" for m in p.modes)
        values = ""
        if p.section not in counted and (p.treatment != "excluded" or TREATMENT[p.section] == "excluded"):
            counted.add(p.section)
            values = str(len(named[p.section]))
        lines.append(f"| {p.section} | {p.title} | {p.treatment} | {modes} | {values} | {p.note} |")
    lines += [
        "",
        f"The table maps {len(trace.TABLE)} provisions of AISC 360-22 Chapters J and K. The deck "
        f"{tally(trace.TABLE)}. It maps {len(trace.APPENDIX3)} provisions of Appendix 3, Fatigue, and "
        f"{tally(trace.APPENDIX3)}.",
        "",
        "## Coverage of Chapters J and K",
        "",
        *coverage_lines(c),
        "",
        "## Values",
        "",
        "A value's page is where `docs/sources/anchors.jsonl` anchors it, and `scripts/verify_sources.py` checks "
        "the page against the document. A value can name several provisions and is listed under each.",
    ]
    for section in IDS:
        if named[section]:
            lines += ["", f"### {section}", "", *value_table(named[section], anchors)]
    shapes = [x for x in inv.read() if x["edition"] == SHAPES]
    on_cells = sum(1 for x in shapes if anchors[x["id"]]["kind"] == "cell")
    lines += ["", "### Other clauses", "",
              "These values' clauses name no traced provision, as a member's slenderness limit in Table B4.1a.", "",
              *value_table(other, anchors), "",
              f"The Shapes Database gives {len(shapes)} more values, the dimensions of the deck's W shapes. "
              f"{on_cells} of them are anchored to their workbook cells."]
    return "\n".join(lines) + "\n"


def listing(words: list[str]) -> str:
    return words[0] if len(words) == 1 else f"{', '.join(words[:-1])} and {words[-1]}"


def coverage_lines(c: dict) -> list[str]:
    j = [s for s in JK if s.startswith("J")]
    j_encoded = [s for s in c["encoded"] if s.startswith("J")]
    j_eqs = [e for e in c["equations"] if e.startswith("J")]
    k_eqs = [e for e in c["equations"] if e.startswith("K")]
    j_cited = [e for e in c["cited"] if e.startswith("J")]
    uncited: dict[str, list[str]] = {}
    for section in JK:
        for label in c["by_section"].get(section, []):
            if label.startswith("J") and label not in c["cited"]:
                uncited.setdefault(section, []).append(label)
    rest = [f"{listing(labels)} in {s} ({TREATMENT[s]})" for s, labels in uncited.items()]
    return [
        f"Petra encodes {len(c['encoded'])} of the {c['provisions']} provisions of Chapters J and K "
        f"({percent(len(c['encoded']), c['provisions'])}) as checks or rules. That is {len(j_encoded)} of Chapter "
        f"J's {len(j)} ({percent(len(j_encoded), len(j))}) and none of Chapter K's {len(JK) - len(j)}. It states "
        f"{len(c['premise'])} as premises ({listing(c['premise'])}) and excludes {len(c['excluded'])} "
        f"({listing(c['excluded'])}).",
        "",
        f"AISC 360-22 numbers {len(c['equations'])} equations in Chapters J and K, {len(j_eqs)} in J and "
        f"{len(k_eqs)} in K (`docs/sources/equations.json`). The inventory cites {len(j_cited)} of Chapter J's "
        f"({percent(len(j_cited), len(j_eqs))}) and none of Chapter K's. The rest of Chapter J's are "
        f"{'; '.join(rest)}.",
    ]


def connections_block() -> str:
    """The provision table of docs/steel_connections.md §4."""
    named, _ = values_by_provision()
    titles = {**CHAPTERS, **{p.section: p.title for p in trace.TABLE if p.section.startswith("K")}}
    lines = [BEGIN, "", "| Section | Content | Checked | Rules | Premises | Excluded | Values |",
             "|---|---|---|---|---|---|---|"]
    for ch, title in titles.items():
        rows = [p for p in trace.TABLE if p.section == ch or p.section.startswith(ch + ".")]
        cols = [", ".join(p.section for p in rows if p.treatment == t) for t in trace.TREATMENTS]
        values = len({x["id"] for p in rows for x in named[p.section]})
        lines.append(f"| {ch} | {title} | " + " | ".join(cols) + f" | {values} |")
    c = coverage()
    lines += ["", "Values counts the registry values, equations and coded rules whose clause names a provision "
              "of the section.", "", *coverage_lines(c)[:1], "",
              f"Of Appendix 3's {len(trace.APPENDIX3)} provisions, the deck {tally(trace.APPENDIX3)} (§4a). "
              "[steel_traceability.md](steel_traceability.md) gives each provision's modes and note, and each "
              "value with the page that states it.", "", END]
    return "\n".join(lines)


def connections(text: str) -> str:
    """docs/steel_connections.md with its generated block replaced."""
    start, end = text.index(BEGIN), text.index(END) + len(END)
    return text[:start] + connections_block() + text[end:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a committed file is stale")
    args = parser.parse_args(argv)
    stale = []
    for path, text in ((TRACEABILITY, traceability()), (CONNECTIONS, connections(CONNECTIONS.read_text(encoding="utf-8")))):
        if path.read_text(encoding="utf-8") != text:
            stale.append(path)
            if not args.check:
                path.write_text(text, encoding="utf-8", newline="\n")
    for path in stale:
        print(f"{'stale' if args.check else 'wrote'} {path.relative_to(ROOT)}")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
